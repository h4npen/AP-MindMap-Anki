def main():
    print("🚀 Generating high quality notes...")
    for note in NOTES_DATA:
        dest_dir = os.path.join(INBOX_DIR, note["cat_dir"])
        os.makedirs(dest_dir, exist_ok=True)
        file_path = os.path.join(dest_dir, note["filename"])
        content = build_markdown(note)
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"  ✅ Created: {note['filename']} in {note['cat_dir']}")

    print("\n📝 Updating docs/README.md...")
    with open(DOCS_README, "r", encoding="utf-8") as f:
        readme_content = f.read()

    # H30春 問35 のエントリも追加定義
    all_entries = [
        {
            "cat_dir": "10_ネットワーク",
            "filename": "net-route-aggregation-h30-q35.md",
            "title_short": "ルート集約（CIDR計算パズル）",
            "q_title": "平成30年春期 問35",
            "q_url": "https://www.ap-siken.com/kakomon/30_haru/q35.html",
            "summary": "『変わる場所だけ2進数！右側ゼロリセットで即完成！』<br>郵便番号の集約。32個の箱パズルで解くネットワーク合体法"
        }
    ]
    for n in NOTES_DATA:
        all_entries.append({
            "cat_dir": n["cat_dir"],
            "filename": n["filename"],
            "title_short": n["title_custom"].split("：")[0],
            "q_title": n["title"],
            "q_url": n["q_url"],
            "summary": n["summary"]
        })

    updated_count = 0
    for item in all_entries:
        cat_dir = item["cat_dir"]
        filename = item["filename"]
        rel_link = f"./inbox/{cat_dir}/{filename}"

        if rel_link in readme_content:
            continue

        cat_name = cat_dir.split("_", 1)[1] if "_" in cat_dir else cat_dir
        # DOTALL を使って改行を含めてマッチさせる
        cat_pattern = rf"(## \d+\. {cat_name}.*?\n\| :---.*?\n)"
        m = re.search(cat_pattern, readme_content, re.DOTALL)
        if m:
            insert_pos = m.end()
            new_row = f"| [{filename}]({rel_link}) | **{item['title_short']}**<br>（[{item['q_title']}]({item['q_url']})） | {item['summary']} | inbox |\n"
            readme_content = readme_content[:insert_pos] + new_row + readme_content[insert_pos:]
            updated_count += 1
            print(f"  ➕ Added to index: {filename}")

    if updated_count > 0:
        with open(DOCS_README, "w", encoding="utf-8") as f:
            f.write(readme_content)
        print(f"🎉 Updated docs/README.md with {updated_count} new entries!")
    else:
        print("ℹ️ All entries already present in docs/README.md.")

if __name__ == "__main__":
    main()
